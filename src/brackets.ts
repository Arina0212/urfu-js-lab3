/**
 * Проверка сбалансированности скобок.
 *
 * Поддерживаются круглые (), квадратные [], фигурные {} и угловые <>.
 * Любые другие символы в строке игнорируются.
 *
 * Правила:
 *  - каждая закрывающая скобка должна закрывать последнюю незакрытую открывающую;
 *  - к концу строки незакрытых скобок остаться не должно.
 *
 * Примеры: "({})" — верно, "({)}" — неверно, "(" — неверно, ")(" — неверно.
 *
 * Алгоритм — стек: открывающую кладём в стек, на закрывающей снимаем вершину
 * и проверяем, что это парная ей скобка.
 *
 * Сложность: O(n) по времени (один проход по строке),
 * O(n) по памяти в худшем случае (строка из одних открывающих скобок).
 */

const PAIRS: Record<string, string> = {
    ')': '(',
    ']': '[',
    '}': '{',
    '>': '<',
};

const OPENING = new Set(Object.values(PAIRS));

export function isBalanced(input: string): boolean {
    const stack: string[] = [];

    for (const char of input) {
        if (OPENING.has(char)) {
            stack.push(char);
            continue;
        }

        if (char in PAIRS) {
            if (stack.pop() !== PAIRS[char]) {
                return false;
            }
        }
    }

    return stack.length === 0;
}
